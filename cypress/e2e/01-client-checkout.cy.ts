import { captureFullPage } from "../support/capture";
import { pasteInput, autofillInput } from "../support/input-helpers";

describe("Cliente: carrito → checkout invitado → pedido real en PostgreSQL",()=>{
  it("Valida consentimiento, datos y creación sin registro",()=>{
    cy.viewport(1280,720);
    cy.visit("/");
    cy.get("body").should("not.contain","generadas por IA").and("not.contain","Fotografías ilustrativas");
    cy.get('[data-testid="store-directions"]').should("have.attr","target","_blank").invoke("attr","href").then(href=>{
      const url=new URL(href!);expect(url.origin).to.equal("https://www.google.com");expect(url.pathname).to.equal("/maps/dir/");
      expect(url.searchParams.get("api")).to.equal("1");expect(url.searchParams.get("destination")).to.equal("1.1464015,-76.6470404");
    });
    cy.get('[data-testid="footer-directions"]').should("have.attr","href").and("include","destination=");
    cy.get('img[src$="branding-2026-10-02/hero.webp"]').should($image=>expect(($image[0] as HTMLImageElement).naturalWidth).to.be.greaterThan(0));
    cy.screenshot("tienda-escritorio",{capture:"viewport"});
    captureFullPage("branding-home-desktop");
    cy.viewport(390,720);
    cy.document().should(document=>expect(document.documentElement.scrollWidth).to.be.at.most(390));
    cy.screenshot("tienda-movil",{capture:"viewport"});
    captureFullPage("branding-home-mobile");
    cy.viewport(1280,720);
    cy.visit("/catalogo");
    cy.get('[data-testid="product-card"] img').should($images => {
      expect($images.length).to.be.greaterThan(0);
      for (const image of $images.toArray()) expect((image as HTMLImageElement).getAttribute("src")).not.to.match(/\.svg$/);
    });
    captureFullPage("branding-catalog-desktop");
    cy.get('[data-testid="product-card"]').filter(':has(button:not(:disabled))').first().find('a').first().click();
    cy.get('[data-testid="quantity-input"]').clear().type("abc").should("have.value","");
    cy.get('[data-testid="add-to-cart"]').first().should("be.disabled");
    cy.get('[data-testid="quantity-input"]').type("1ex.,-+").should("have.value","1");
    pasteInput('[data-testid="quantity-input"]', "7x", true).should("eq",false);
    cy.get('[data-testid="quantity-input"]').should("have.value","1");
    cy.get('[data-testid="quantity-input"]').clear().type("999999");
    cy.get('[data-testid="add-to-cart"]').first().should("be.disabled");
    cy.get('[data-testid="quantity-error"]').should("contain","cantidad entera");
    cy.get('[data-testid="quantity-input"]').clear().type("1").should("have.attr","aria-invalid","false");
    cy.get('[data-testid="add-to-cart"]').first().click();
    cy.contains("Añadido al carrito con éxito").should("be.visible");
    cy.get('[data-testid="cart-count"]').should("contain","1");
    cy.reload();
    cy.get('[data-testid="cart-count"]').should("contain","1");
    let checkoutRequests=0;
    cy.intercept("POST","/api/orders",req=>{checkoutRequests++;req.continue();});
    cy.visit("/checkout");
    cy.get('[data-testid="checkout-submit"]').click();
    cy.get('[data-testid="checkout-name"]').invoke("prop","validationMessage").should("eq","Completa este campo.");
    cy.screenshot("validation-checkout",{capture:"viewport"});
    cy.get('[data-testid="checkout-name"]').type("An");
    cy.get('[data-testid="checkout-name"]').invoke("prop","validationMessage").should("eq","Ingresa al menos 3 caracteres.");
    cy.get('[data-testid="checkout-name"]').clear().type("Ana123 Gómez").should("have.value","Ana Gómez");
    pasteInput('[data-testid="checkout-name"]', "Ana123 Gómez", true).should("eq",false);
    cy.get('[data-testid="checkout-name"]').should("have.value","Ana Gómez");
    cy.get('[data-testid="checkout-name"]').clear().type("María-José D’Angelo.").should("have.value","María-José D’Angelo.");
    pasteInput('[data-testid="checkout-name"]', "Ana María Gómez", true).should("eq",true);
    cy.get('[data-testid="checkout-name"]').should("have.value","Ana María Gómez");
    autofillInput('[data-testid="checkout-name"]', "Ana123 Gómez");
    cy.get('[data-testid="checkout-name"]').should("have.value","Ana María Gómez");
    cy.get('[data-testid="checkout-name"]').invoke("prop","validationMessage").should("eq","");
    cy.get('[data-testid="checkout-phone"]').type("300abc1234567").should("have.value","3001234567");
    pasteInput('[data-testid="checkout-phone"]', "300abc1234567", true).should("eq",false);
    cy.get('[data-testid="checkout-city"]').clear().type("Mocoa123").should("have.value","Mocoa");
    pasteInput('[data-testid="checkout-city"]', "Mocoa123", true).should("eq",false);
    cy.get('[data-testid="checkout-city"]').should("have.value","Mocoa");
    cy.get('[data-testid="checkout-phone"]').clear().type("+57 300 123 4567");
    cy.get('[data-testid="checkout-phone"]').invoke("prop","validationMessage").should("eq","");
    cy.get('[data-testid="checkout-email"]').type("correo-invalido");
    cy.get('[data-testid="checkout-email"]').invoke("prop","validationMessage").should("eq","Ingresa un correo electrónico válido.");
    cy.get('[data-testid="checkout-email"]').clear().type("ana@example.com");
    cy.get('[data-testid="checkout-email"]').invoke("prop","validationMessage").should("eq","");
    cy.get('[data-testid="checkout-address"]').type("Calle 12 # 5-34, barrio Centro");
    cy.get('[data-testid="checkout-city"]').clear().type("Mocoa");
    cy.get('textarea[name="notes"]').type("Apartamento 302, entregar después de las 5.");
    captureFullPage("input-blocking-checkout");
    cy.get('[data-testid="checkout-submit"]').click();
    cy.get('[data-testid="checkout-terms"]').invoke("prop","validationMessage").should("eq","Debes aceptar los términos y condiciones para continuar.");
    cy.get('[data-testid="checkout-terms"]').check();
    cy.get('[data-testid="checkout-submit"]').click();
    cy.get('[data-testid="checkout-data-consent"]').then($input=>expect(($input[0] as HTMLInputElement).validity.valueMissing).to.equal(true));
    cy.get('[data-testid="checkout-data-consent"]').invoke("prop","validationMessage").should("eq","Debes autorizar el tratamiento de tus datos personales para continuar.");
    cy.location("pathname").should("eq","/checkout");
    cy.then(()=>expect(checkoutRequests).to.equal(0));
    cy.get('[data-testid="checkout-data-consent"]').check();
    cy.get('[data-testid="checkout-data-consent"]').invoke("prop","validationMessage").should("eq","");
    cy.intercept("POST","/api/orders").as("createOrder");
    cy.get('[data-testid="checkout-submit"]').click();
    cy.wait("@createOrder").then(({response})=>{
      expect(response?.statusCode).to.equal(201);
      const id=response!.body.orderId;
      cy.location("pathname").should("eq","/pedido/"+id);
      cy.get('[data-testid="order-status"]').should("contain","Pendiente de pago");
      cy.task("orderStatus",id).should("eq","PENDING");
    });
  });
});

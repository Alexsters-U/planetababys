import { captureFullPage } from "../support/capture";
import { pasteInput, autofillInput } from "../support/input-helpers";

describe("Administración: sesión HttpOnly, CRUD y logística persistente",{baseUrl:"http://127.0.0.1:3100"},()=>{
  it("Crea, modifica y elimina producto; pasa un pedido a Empacado y Enviado",()=>{
    const name="Producto UI "+Date.now();
    cy.visit("/admin/productos");
    cy.location("pathname").should("eq","/admin/login");
    cy.get('[data-testid="admin-login-submit"]').click();
    cy.get('[data-testid="admin-email"]').invoke("prop","validationMessage").should("eq","Completa este campo.");
    cy.screenshot("validation-admin-login",{capture:"viewport"});
    cy.get('[data-testid="admin-email"]').type("correo-invalido");
    cy.get('[data-testid="admin-email"]').invoke("prop","validationMessage").should("eq","Ingresa un correo electrónico válido.");
    cy.get('[data-testid="admin-email"]').clear().type("test@admin.com");
    cy.get('[data-testid="admin-email"]').invoke("prop","validationMessage").should("eq","");
    cy.get('[data-testid="admin-password"]').type("password",{log:false});
    cy.get('[data-testid="admin-login-submit"]').click();
    cy.location("pathname").should("eq","/admin/productos");
    cy.getCookie("pbb_admin_token").then(cookie=>expect(cookie?.httpOnly).to.equal(true));
    cy.get('[data-testid="admin-result-count"]').should("not.contain","Actualizando");
    cy.get('[data-testid="admin-search"]').type("Biberón{enter}");
    cy.get('[data-testid="admin-filter-category"]').select("lactancia");
    cy.get('[data-testid="product-row"]').should("have.length",1).and("contain","Biberón");
    cy.get('[data-testid="edit-product-button"]').click();
    cy.intercept("PATCH","/api/admin/products/*").as("saveBrandImage");
    cy.get('[data-testid="product-form-submit"]').click();
    cy.wait("@saveBrandImage").its("response.statusCode").should("eq",200);
    cy.get('[data-testid="admin-search"]').clear().type("producto-inexistente-xyz{enter}");
    cy.get('[data-testid="products-table"]').should("contain","No hay productos que coincidan");
    cy.get('[data-testid="admin-result-count"]').should("contain","0–0 de 0");
    cy.get('[data-testid="admin-clear-filters"]').click();
    cy.get('[data-testid="admin-page-size"]').select("10");
    cy.get('[data-testid="product-row"]').should("have.length",10);
    cy.get('nav[aria-label="Paginación"]').contains("button","Siguiente").click();
    cy.get('nav[aria-label="Paginación"]').should("contain","Página 2");
    cy.get('[data-testid="admin-result-count"]').should("contain","Mostrando 11");
    captureFullPage("admin-products-filters");
    cy.viewport(390,720);
    cy.document().should(document=>expect(document.documentElement.scrollWidth).to.be.at.most(390));
    captureFullPage("admin-products-mobile");
    cy.viewport(1280,720);
    cy.get('[data-testid="admin-clear-filters"]').click();
    cy.get('[data-testid="new-product-button"]').click();
    cy.get('[data-testid="product-form-submit"]').click();
    cy.get('[data-testid="product-name-input"]').invoke("prop","validationMessage").should("eq","Completa este campo.");
    cy.screenshot("validation-product-form",{capture:"viewport"});
    cy.get('[data-testid="product-name-input"]').type(name);
    cy.get('[data-testid="product-name-input"]').invoke("prop","validationMessage").should("eq","");
    let productRequests=0;
    cy.intercept("POST","/api/admin/products",req=>{productRequests++;req.continue();});
    cy.get('[data-testid="product-price-input"]').type("25abc").should("have.value","25");
    pasteInput('[data-testid="product-price-input"]', "25000abc", true).should("eq",false);
    cy.get('[data-testid="product-price-input"]').should("have.value","25");
    autofillInput('[data-testid="product-price-input"]', "25000abc");
    cy.get('[data-testid="product-price-input"]').should("have.value","25");
    cy.get('[data-testid="product-stock-input"]').clear().type("7x.,-+").should("have.value","7");
    pasteInput('[data-testid="product-stock-input"]', "7x", true).should("eq",false);
    cy.get('[data-testid="product-stock-input"]').should("have.value","7");
    cy.get('[data-testid="product-price-input"]').clear().type("abc").should("have.value","");
    cy.get('[data-testid="product-form-submit"]').click();
    cy.then(()=>expect(productRequests).to.equal(0));
    cy.get('[data-testid="product-price-input"]').invoke("prop","validationMessage").should("eq","Completa este campo.");
    cy.get('[data-testid="product-price-input"]').clear().type("25000,50abc9.").should("have.value","25000,50");
    pasteInput('[data-testid="product-price-input"]', "25000.75", true).should("eq",true);
    cy.get('[data-testid="product-price-input"]').should("have.value","25000.75");
    pasteInput('[data-testid="product-price-input"]', "25000,50", true).should("eq",true);
    cy.get('[data-testid="product-price-input"]').invoke("prop","validationMessage").should("eq","");
    cy.get('[data-testid="product-stock-input"]').clear().type("7");
    cy.screenshot("input-blocking-product",{capture:"viewport"});
    cy.intercept("POST","/api/admin/products").as("createProduct");
    cy.get('[data-testid="product-form-submit"]').click();
    cy.wait("@createProduct").its("response.statusCode").should("eq",201);
    cy.task("productByName",name).then((p:any)=>{expect(p.priceCents).to.equal(2500050);expect(p.stock).to.equal(7);});
    cy.contains('[data-testid="product-row"]',name).within(()=>cy.get('[data-testid="edit-product-button"]').click());
    cy.get('[data-testid="product-price-input"]').clear().type("28000");
    cy.get('[data-testid="product-stock-input"]').clear().type("9");
    cy.intercept("PATCH","/api/admin/products/*").as("updateProduct");
    cy.get('[data-testid="product-form-submit"]').click();
    cy.wait("@updateProduct").its("response.statusCode").should("eq",200);
    cy.task("productByName",name).then((p:any)=>{expect(p.priceCents).to.equal(2800000);expect(p.stock).to.equal(9);});
    cy.contains('[data-testid="product-row"]',name).within(()=>cy.get('[data-testid="delete-product-button"]').click());
    cy.intercept("DELETE","/api/admin/products/*").as("deleteProduct");
    cy.get('[data-testid="confirm-delete"]').click();
    cy.wait("@deleteProduct").its("response.statusCode").should("eq",200);
    cy.task("productByName",name).should("be.null");
    cy.task("createPaidOrder").then((fixture:any)=>{
      cy.visit("/admin/pedidos");
      cy.get('[data-testid="admin-search"]').type(fixture.reference+"{enter}");
      cy.get('[data-testid="order-row"]').should("have.length",1);
      cy.contains('[data-testid="order-row"]',fixture.reference).within(()=>{
        cy.get('[data-testid="order-row-status"]').should("contain","Recibido");
        cy.get('[data-testid="order-status-select"]').select("PACKED");
      });
      cy.contains('[data-testid="order-row"]',fixture.reference).within(()=>cy.get('[data-testid="order-row-status"]').should("contain","Empacado"));
      cy.contains('[data-testid="order-row"]',fixture.reference).within(()=>cy.get('[data-testid="order-status-select"]').select("SHIPPED"));
      cy.contains('[data-testid="order-row"]',fixture.reference).within(()=>cy.get('[data-testid="order-row-status"]').should("contain","Enviado"));
      cy.task("orderStatus",fixture.orderId).should("eq","SHIPPED");
      cy.get('[data-testid="admin-filter-status"]').select("SHIPPED");
      cy.get('[data-testid="order-row"]').should("have.length",1);
      captureFullPage("admin-orders-filters");
      cy.task("cleanupFixture",fixture);
    });
  });
});
